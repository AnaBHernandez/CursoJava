/**
 * Ejercicio1 - Declaración e inicialización de variables
 * Este ejercicio introduce los conceptos básicos de:
 * - Declaración de variables
 * - Inicialización de variables
 * - Tipos de datos primitivos (int) y objetos (String)
 * - Salida por consola con System.out.println()
 */
public class Ejercicio1 {
    
    public static void main(String[] args) {
        // Declaración e inicialización en una línea
        int edad = 47; // Variable de tipo entero
        
        // Declaración separada de la inicialización
        String nombre; // Declaración de variable String
        nombre = "Ana Belén"; // Asignación de valor
        
        // Mostrar los valores por consola
        System.out.println("Nombre: " + nombre);
        System.out.println("Edad: " + edad);
    }
}